import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const files = ['.env', 'backend/.env'].map((name) => new URL(name, root))
const existing = files.find((file) => existsSync(file))
const content = existing
  ? readFileSync(existing, 'utf8')
  : `# Local development only. Generated by pnpm run setup:local.\nJWT_SECRET=${randomBytes(32).toString('hex')}\n`
for (const file of files) {
  if (existsSync(file)) continue
  writeFileSync(file, content, { mode: 0o600, flag: 'wx' })
  console.log(`Created ${fileURLToPath(file).slice(fileURLToPath(root).length)}`)
}
console.log('Local secrets are ready. Next: pnpm run db:migrate, then pnpm run dev.')
